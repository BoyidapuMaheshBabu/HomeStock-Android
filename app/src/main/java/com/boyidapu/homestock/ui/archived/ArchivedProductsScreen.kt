@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun ArchivedProductsScreen(
    viewModel: ArchivedProductsViewModel,
    onBack: () -> Unit
) {
    val uiState by viewModel.uiState.collectAsState()
    val snackbarHostState = remember { SnackbarHostState() }

    LaunchedEffect(Unit) {
        viewModel.eventFlow.collect { event ->
            when (event) {
                is ArchivedEvent.ShowMessage -> {
                    snackbarHostState.showSnackbar(event.message)
                }
            }
        }
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = {
                    Text(
                        text = "Archived Products",
                        fontWeight = FontWeight.Bold,
                        color = DeepTeal
                    )
                },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(
                            imageVector = Icons.AutoMirrored.Filled.ArrowBack,
                            contentDescription = "Back",
                            tint = DeepTeal
                        )
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = MaterialTheme.colorScheme.background
                )
            )
        },
        snackbarHost = { SnackbarHost(hostState = snackbarHostState) }
    ) { paddingValues ->
        Box(
            modifier = Modifier
                .fillMaxSize()
                .padding(paddingValues)
        ) {
            if (uiState.archivedProducts.isEmpty()) {
                Box(
                    modifier = Modifier
                        .fillMaxSize()
                        .padding(24.dp),
                    contentAlignment = Alignment.Center
                ) {
                    Text(
                        text = "No archived products.\nProducts with transaction history and zero stock can be archived from the category menu.",
                        fontSize = 15.sp,
                        color = MutedSageGray,
                        textAlign = TextAlign.Center
                    )
                }
            } else {
                LazyColumn(
                    modifier = Modifier
                        .fillMaxSize()
                        .padding(horizontal = 20.dp, vertical = 12.dp),
                    verticalArrangement = Arrangement.spacedBy(12.dp)
                ) {
                    items(
                        items = uiState.archivedProducts,
                        key = { it.product.id }
                    ) { item ->
                        ArchivedProductCard(
                            item = item,
                            onRestore = { viewModel.restoreProduct(item.product.id) }
                        )
                    }
                }
            }
        }
    }
}

@Composable
private fun ArchivedProductCard(
    item: ProductWithStock,
    onRestore: () -> Unit
) {
    Card(
        colors = CardDefaults.cardColors(containerColor = CleanWhite),
        shape = RoundedCornerShape(16.dp),
        elevation = CardDefaults.cardElevation(defaultElevation = 2.dp),
        modifier = Modifier.fillMaxWidth()
    ) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(16.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Column(modifier = Modifier.weight(1f)) {
                Text(
                    text = item.product.name,
                    fontSize = 16.sp,
                    fontWeight = FontWeight.Bold,
                    color = ForestCharcoal
                )

                Spacer(modifier = Modifier.height(4.dp))

                Text(
                    text = "Category: ${item.product.category.displayName}",
                    fontSize = 13.sp,
                    color = MutedSageGray
                )
            }

            OutlinedButton(
                onClick = onRestore,
                colors = ButtonDefaults.outlinedButtonColors(contentColor = DeepTeal)
            ) {
                Text("Restore")
            }
        }
    }
}
